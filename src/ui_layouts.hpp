#pragma once

// UI layout notes and the widget names plugin.cpp shares with the companion
// mpq layouts of the Quyen19492 Item Sorting plugin.
//
// Design note (v1 scope, see README "Known gaps" -- flagged for sign-off):
// D2RLPlugin::WidgetService has no "set widget text" call (only
// getInputText, which reads InputTextBoxWidget content, and
// setWidgetVisible/setWidgetEnabled). There is therefore no supported way to
// push freshly-computed text (an item count, an error detail) into an
// already-registered JSON widget at runtime. The toast panel (Toasthd.json) works
// around this the only way the SDK allows: every possible message is a
// separate TextBoxWidget baked into the JSON up front, and showing a result
// means calling setWidgetVisible(true) on exactly one of them (and false on
// the rest) rather than setting text. Exact item/tab counts from Auto Sort
// go to the plugin's log file (PluginContext::LogInfo) instead of the toast
// for the same reason -- there are too many possible values to enumerate as
// widgets. The "selected tab" pointer (see plugin.cpp) IS small and bounded
// (kMaxDisplayableTab+1 values) so it gets the enumerated-widget treatment.

#include <cstdint>
#include <string>

namespace ItemSorting::UiLayouts {

inline constexpr const char* kPluginId = "quyen19492-item-sorting";

// ---------------------------------------------------------------------
// Buttons: the plugin no longer attaches its own strip to PlayerInventory.
// The Auto Sort / Add Page / Remove Page buttons live inside the mod's
// shared-stash dialog (BankExpansionLayout > basicstash_container >
// SharedStashTabContainer), inserted by tools/patch_mod_stash_layout.py,
// because the SDK can only attach child layouts to StockPanel::PlayerInventory
// and a plugin companion MPQ may not override native layouts. Their sprites
// (stash_btn_*.sprite, generated by tools/gen_stash_button_sprites.py) ship
// in this plugin's companion MPQ under
// data/hd/global/ui/d2rloader/quyen19492-item-sorting/, and their tooltips use
// "@quyen19492-item-sorting:<Key>" entries from its strings.json. Each button
// fires PanelManager:TogglePanel:quyen19492-item-sorting/Action<Name>; see the
// g_action*Panel comment in plugin.cpp.
//
// The single-grid Sort buttons follow the same pattern:
//   - personal stash and Horadric Cube: inserted into the mod's own
//     bankexpansionlayouthd.json / horadriccubelayouthd.json by
//     tools/patch_mod_stash_layout.py (ActionSortPersonalStash /
//     ActionSortCube);
//   - inventory: a plugin child layout on StockPanel::PlayerInventory --
//     d2rl-quyen19492-item-sorting.mpq/data/global/ui/layouts/
//     quyen19492-item-sorting/InventoryToolshd.json, a single ButtonWidget
//     firing ActionSortInventory. Registered in D2RLoaderLoadPlugin.
// All three reuse the stash_btn_autosort sprite.

// ---------------------------------------------------------------------
// Toast panel: the plugin's own result notification, per the user's explicit
// choice of "plugin's own panel/toast" over D2RLoader's console or the D2R
// chat box (see README). The layout itself is a static file in the companion
// mpq: d2rl-quyen19492-item-sorting.mpq/data/global/ui/layouts/
// quyen19492-item-sorting/Toasthd.json. It must contain one hidden
// TextBoxWidget per OutcomeMessageWidgetName() and per TabWidgetName(0..
// kMaxDisplayableTab+1); plugin.cpp finds them by these names, and
// tests/grid_sort_test.cpp checks the file has every one of them.

enum class OutcomeMessage : uint32_t {
	AutoSortOk = 0,
	AutoSortDisabled,
	AutoSortNotEnoughTabs,
	AutoSortNoRoom,
	AutoSortSetNoRoom,
	AutoSortUnknownMode,
	BlankMoved,
	NoBlankTab,
	PageRemoved,
	CurrentNotEmpty,
	OutOfRange,
	MultiplayerClientUnsupported,
	TabSelected,
	PageUnknown,
	InternalError,
	// Single-grid Sort (personal stash / inventory / cube).
	GridSortOk,
	GridSortDisabled,
	GridSortConfigError,
	GridSortNoRoom,
	GridSortRejected,
	GridSortTooFull,
	Count, // not a real message; array size marker
};

inline const char* OutcomeMessageWidgetName(OutcomeMessage msg) {
	switch (msg) {
		case OutcomeMessage::AutoSortOk: return "MsgAutoSortOk";
		case OutcomeMessage::AutoSortDisabled: return "MsgAutoSortDisabled";
		case OutcomeMessage::AutoSortNotEnoughTabs: return "MsgAutoSortNotEnoughTabs";
		case OutcomeMessage::AutoSortNoRoom: return "MsgAutoSortNoRoom";
		case OutcomeMessage::AutoSortSetNoRoom: return "MsgAutoSortSetNoRoom";
		case OutcomeMessage::AutoSortUnknownMode: return "MsgAutoSortUnknownMode";
		case OutcomeMessage::BlankMoved: return "MsgBlankMoved";
		case OutcomeMessage::NoBlankTab: return "MsgNoBlankTab";
		case OutcomeMessage::PageRemoved: return "MsgPageRemoved";
		case OutcomeMessage::CurrentNotEmpty: return "MsgCurrentNotEmpty";
		case OutcomeMessage::OutOfRange: return "MsgOutOfRange";
		case OutcomeMessage::MultiplayerClientUnsupported: return "MsgMultiplayerClientUnsupported";
		case OutcomeMessage::TabSelected: return "MsgTabSelected";
		case OutcomeMessage::PageUnknown: return "MsgPageUnknown";
		case OutcomeMessage::GridSortOk: return "MsgGridSortOk";
		case OutcomeMessage::GridSortDisabled: return "MsgGridSortDisabled";
		case OutcomeMessage::GridSortConfigError: return "MsgGridSortConfigError";
		case OutcomeMessage::GridSortNoRoom: return "MsgGridSortNoRoom";
		case OutcomeMessage::GridSortRejected: return "MsgGridSortRejected";
		case OutcomeMessage::GridSortTooFull: return "MsgGridSortTooFull";
		case OutcomeMessage::InternalError:
		case OutcomeMessage::Count: return "MsgInternalError";
	}
	return "MsgInternalError";
}

// Generous enough for any realistic shared-stash tab count; beyond this the
// toast just shows "tab 24+" rather than growing the widget list further.
inline constexpr uint32_t kMaxDisplayableTab = 23;

inline std::string TabWidgetName(uint32_t tab) {
	return tab <= kMaxDisplayableTab ? ("MsgTab" + std::to_string(tab)) : std::string("MsgTabOverflow");
}

}
